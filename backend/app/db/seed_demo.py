def ensure_demo_data_seeded(client: QdrantClient, embedder: Any = None, collection: str = "quorix_chunks") -> None:
    """Seed benchmark knowledge chunks if the collection is empty."""
    try:
        if client.collection_exists(collection):
            count = client.count(collection, exact=True).count
            if count > 0:
                return

        # Use precomputed vectors if available to avoid heavy in-memory embedder startup
        vectors = [DEMO_VECTORS.get(c["chunk_id"]) for c in DEMO_CHUNKS]
        if any(v is None for v in vectors):
            if embedder is not None:
                texts = [f"{c['title']} ({c['source_type']})\n{c['text']}" for c in DEMO_CHUNKS]
                vectors = embedder.embed_documents(texts)
            else:
                return

        if not vectors or not vectors[0]:
            return
        dim = len(vectors[0])

        if not client.collection_exists(collection):
            client.create_collection(
                collection_name=collection,
                vectors_config=qm.VectorParams(size=dim, distance=qm.Distance.COSINE),
            )

        # Upsert points
        points = []
        for idx, (chunk, vec) in enumerate(zip(DEMO_CHUNKS, vectors)):
            point_id = str(uuid.uuid5(uuid.NAMESPACE_DNS, chunk["chunk_id"]))
            points.append(
                qm.PointStruct(
                    id=point_id,
                    vector=vec,
                    payload=chunk,
                )
            )

        client.upsert(collection_name=collection, points=points, wait=True)
        log.info("Successfully seeded %d demo chunks into collection %s", len(points), collection)
    except Exception as exc:
        log.warning("Could not seed demo knowledge base into collection %s: %s", collection, exc)
